import assert from "node:assert/strict";
import { chromium } from "playwright-chromium";

const app = process.env.TEST_APP_URL;
assert(app && /^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(app), "Set TEST_APP_URL to an isolated local app with disposable Postgres/Redis and no worker");
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
let page;
try {
  const context = await browser.newContext();
  page = await context.newPage();
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  const suffix = Date.now();
  const company = `Workflow Lab ${suffix}`;
  const email = `workflow-${suffix}@example.test`;
  const password = "Disposable-Workflow-Test-123";
  const registration = await context.request.post(`${app}/api/register`, { data: { name: "Workflow Test", email, password } });
  assert.equal(registration.status(), 201);
  await page.goto(`${app}/login`);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL(`${app}/targets`);
  await page.getByRole("button", { name: "Create Target", exact: true }).click();
  await page.getByLabel("Company / Program name *", { exact: true }).fill(company);
  assert.equal(await page.locator("form").evaluate(form => form.checkValidity()), false);
  await page.getByLabel(/^Required User-Agent/).fill("Workflow-Required/1.0");
  await page.getByLabel("Low", { exact: true }).fill("100.10");
  const scope = page.getByRole("group", { name: "Scope", exact: true });
  await scope.getByRole("button", { name: "+ Add host", exact: true }).click();
  await page.getByLabel("Scope FQDN 1", { exact: true }).fill("WWW.Example.test.");
  await scope.getByRole("button", { name: "+ Add host", exact: true }).click();
  await page.getByLabel("Scope FQDN 2", { exact: true }).fill("*.example.test");
  const out = page.getByRole("group", { name: "Out of Scope", exact: true });
  await out.getByRole("button", { name: "+ Add host", exact: true }).click();
  await page.getByLabel("Out of Scope FQDN 1", { exact: true }).fill("admin.example.test");
  await page.getByRole("group", { name: /^Non-qualifying vulnerabilities/ }).getByLabel("XSS", { exact: true }).check();
  await page.getByRole("button", { name: "Create Target", exact: true }).click();
  await page.waitForURL(/\/targets\/[^/]+$/);
  const programId = new URL(page.url()).pathname.split("/").at(-1);
  await page.getByRole("heading", { name: company, exact: true }).waitFor();
  assert((await page.locator("body").innerText()).includes("Scope — 2 hosts"));
  assert(!(await page.locator("body").innerText()).includes(programId));
  await page.getByRole("link", { name: "Open Scope →", exact: true }).click();
  await page.waitForURL(`${app}/scopes/${programId}`);
  await page.getByRole("button", { name: "Scope — 2 hosts", exact: true }).waitFor();
  const addHost = async host => {
    await page.getByRole("button", { name: "+ Add host", exact: true }).click();
    await page.getByRole("textbox", { name: "FQDN", exact: true }).fill(host);
    await page.getByRole("button", { name: "Save", exact: true }).click();
  };
  await addHost("api.example.test");
  await page.getByRole("button", { name: "Scope — 3 hosts", exact: true }).waitFor();
  await addHost("api.example.test");
  await page.getByRole("alert").filter({ hasText: "already in Scope" }).waitFor();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  const apiCard = page.locator(".ui-card").filter({ has: page.getByText("api.example.test", { exact: true }) });
  await apiCard.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByRole("textbox", { name: "FQDN", exact: true }).fill("new.example.test");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  const newCard = page.locator(".ui-card").filter({ has: page.getByText("new.example.test", { exact: true }) });
  await newCard.getByRole("button", { name: "Remove from scope", exact: true }).click();
  await page.getByRole("button", { name: "Scope — 2 hosts", exact: true }).waitFor();
  await addHost("admin.example.test");
  await page.getByRole("button", { name: "Scope — 3 hosts", exact: true }).waitFor();
  await page.getByRole("button", { name: "Out of scope — 1 hosts", exact: true }).click();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByRole("textbox", { name: "FQDN", exact: true }).fill("admin.example.test.");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("button", { name: "Remove", exact: true }).click();
  await page.getByRole("button", { name: "Out of scope — 0 hosts", exact: true }).waitFor();
  await addHost("admin.example.test");
  await page.getByRole("button", { name: "Out of scope — 1 hosts", exact: true }).waitFor();
  await page.getByRole("link", { name: "Target information →", exact: true }).click();
  await page.getByRole("button", { name: "Edit Target", exact: true }).click();
  await page.getByLabel(/^Required User-Agent/).fill("Workflow-Required/2.0");
  await page.getByRole("button", { name: "Save Target", exact: true }).click();
  await page.getByRole("button", { name: "Edit Target", exact: true }).waitFor();
  await page.getByText("Workflow-Required/2.0", { exact: true }).waitFor();
  await page.getByRole("link", { name: "Start Recon →", exact: true }).click();
  await page.waitForURL(/\/recon/);
  await page.getByLabel("Host", { exact: true }).locator("option").first().waitFor({ state: "attached" });
  const choices = await page.getByLabel("Host", { exact: true }).locator("option").allTextContents();
  assert.deepEqual(choices, ["www.example.test"]);
  await page.getByText("Workflow-Required/2.0", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Start Recon", exact: true }).click();
  await page.waitForURL(/\/hosts\/[^/]+$/);
  await page.getByRole("heading", { name: /www\.example\.test/ }).waitFor();
  await page.getByText("En file d’attente", { exact: true }).waitFor();
  await page.getByRole("link", { name: /^Findings \(/ }).click();
  await page.getByRole("heading", { name: "Findings", level: 1, exact: true }).waitFor();
  await page.getByRole("link", { name: "← Host", exact: true }).click();
  await page.waitForURL(/\/hosts\/[^/]+$/);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: process.env.UI_SCREENSHOT_PATH ?? "/tmp/bughunter-target-workflow.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile viewport must not overflow horizontally");
  await page.screenshot({ path: "/tmp/bughunter-target-workflow-mobile.png", fullPage: true });
  console.log("Browser workflow passed: create, required UA, rewards, scope add/edit/remove, duplicates, exclusions, program edit, selectors, enqueue and historical navigation.");
} catch (error) {
  if (page) {
    console.error("Browser state at failure:", await page.locator("body").innerText());
    await page.screenshot({ path: "/tmp/bughunter-workflow-failure.png", fullPage: true });
  }
  throw error;
} finally { await browser.close(); }
